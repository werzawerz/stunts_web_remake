// node tools/stunts/gen-cars.mjs  →  writes src/physics/cars.generated.ts
// Converts the physics parameters of the original cars (read from the user's local copy) into our
// CarSpec units. Only numbers are carried over; names, looks and everything else are our own.
// Unit conversions (wiki.stunts.hu/wiki/Car_model_physics, Car_parameters):
//   mass unit ≈ 103.375 lb, torque unit = 4 lbf·ft per byte, speed(mph) = 256·rpm / ratio,
//   braking 0x100 ≈ 8.94 m/s², grip 0x100 ≈ 1.198 g, top speed: drag·v²/2 = torque·ratio (mph).
import { writeFileSync } from 'node:fs';
import { loadCars } from './cars.mjs';

const LB = 0.45359237;
const LBFFT = 1.3558179;
const MPH = 0.44704;
const UNIT = 0.3048 / 5;

const MASS = 103.375 * LB; // kg per mass unit
const TORQUE = 4 * LBFFT; // N·m per torque byte
const RATIO = 256 * MPH; // raw ratio → rpm per (m/s)
// Engine force in our model: F = T·(2π/60)·ratio. Matching the original's top-speed balance
// gives drag (N per (m/s)^2) = raw drag × TORQUE·(2π/60)/RATIO / 2 / MPH².
const DRAG = (TORQUE * ((2 * Math.PI) / 60)) / RATIO / 2 / (MPH * MPH);

// Our own names: each car keeps the character of an original, not its identity.
const NAMES = {
  NSX: 'Kestrel V6',
  Audi: 'Rallye 5T',
  Coun: 'Toro V12',
  GTO: 'Rosso Berlinetta',
  Jag: 'Panther LM',
  Lanc: 'Integrale HF',
  L002: 'Bull 4x4',
  962: 'Spyder Group C',
  PC4: 'Flat-Six 4',
  INDY: 'Indy Racer',
  'ZR-1': 'Stingray V8',
};

const r = (x, d = 3) => Number(x.toFixed(d));
const cars = loadCars(process.argv[2] ?? 'original_game/STUNTS11').map((c) => {
  const s = c.simd;
  const [fx, , fz] = s.wheels[0];
  return {
    id: c.id.toLowerCase().replace(/[^a-z0-9]/g, ''),
    name: NAMES[c.id] ?? c.id,
    mass: r(s.mass * MASS, 1),
    gearRatios: s.ratios.map((x) => r(x / RATIO)),
    idleRpm: s.idleRpm,
    downshiftRpm: s.downRpm,
    upshiftRpm: s.upRpm,
    maxRpm: s.maxRpm,
    torque: s.torque.map((b) => r(b * TORQUE, 1)),
    idleTorque: r(s.idleTorque * TORQUE, 1),
    drag: r(s.drag * DRAG, 4),
    brakeDecel: r((8.94 * s.brakes) / 256),
    grip: r((1.198 * s.grip) / 256),
    surfaceGrip: s.surfaceGrip.map((g) => r(g / 256)),
    wheelbase: r(((2 * Math.abs(fz)) / 64) * UNIT),
    halfTrack: r((Math.abs(fx) / 64) * UNIT),
    claims: c.claims,
  };
});

const out = `// GENERATED by tools/stunts/gen-cars.mjs from the original car data (numbers only). Do not edit.
import type { OriginalCarData } from './car';

export const ORIGINAL_CARS: OriginalCarData[] = ${JSON.stringify(cars, null, 2)};
`;
writeFileSync('src/physics/cars.generated.ts', out);
console.log(`wrote ${cars.length} cars; drag factor ${DRAG.toFixed(5)}`);
