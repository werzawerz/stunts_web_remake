// node tools/stunts/gen-editor.mjs [path/to/TEDIT.PRE]
//   → writes src/track/editorTables.generated.ts
// Reads the original track editor's tables from TEDIT.PRE: the palette pages ("pbox", ten 6x6
// grids of element codes laid out like little maps, 254/255 marking the other tiles of a bigger
// piece), each element's palette/map icon ("snam", drawn at runtime from the player's own
// SDTEDIT.PES) and its name ("tnam" → the "e???" strings). Only these factual tables are kept.
import { readFileSync, writeFileSync } from 'node:fs';
import { parseResources, unpack } from './formats.mjs';

const file = process.argv[2] ?? 'original_game/STUNTS11/TEDIT.PRE';
const res = parseResources(unpack(new Uint8Array(readFileSync(file))));
const text = (b) => String.fromCharCode(...b).replace(/\0.*$/s, '');

const pbox = res.get('pbox');
const pages = [];
for (let p = 1; p < pbox.length / 36; p++) pages.push([...pbox.subarray(p * 36, p * 36 + 36)]);

const snam = res.get('snam');
const tnam = res.get('tnam');
const count = snam.length / 4;
const icons = [];
const names = [];
for (let c = 0; c < count; c++) {
  icons.push(text(snam.subarray(c * 4, c * 4 + 4)));
  const key = `e${text(tnam.subarray(c * 3, c * 3 + 3))}`;
  names.push(res.has(key) ? text(res.get(key)) : '');
}

const rows = (a, per) => {
  const out = [];
  for (let i = 0; i < a.length; i += per) out.push(`    ${a.slice(i, i + per).map((v) => JSON.stringify(v)).join(', ')},`);
  return out.join('\n');
};

const ts = `// GENERATED by tools/stunts/gen-editor.mjs from the original track editor's tables. Do not edit.
// The palette pages (6x6 element codes each, row by row from the top; 0 = the blank square that
// erases, 254/255 = the other tiles of a bigger piece), and per element code its icon in
// SDTEDIT.PES (read at runtime from the player's files) and the name the editor shows.

export const PALETTE_PAGES: number[][] = [
${pages.map((p) => `  [\n${rows(p, 6)}\n  ],`).join('\n')}
];

export const ELEMENT_ICONS: string[] = [
${rows(icons, 12)}
];

export const ELEMENT_NAMES: string[] = [
${rows(names, 6)}
];
`;
writeFileSync('src/track/editorTables.generated.ts', ts);
console.log(`${pages.length} pages, ${count} element codes`);
