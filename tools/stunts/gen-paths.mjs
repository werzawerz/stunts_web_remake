// node tools/stunts/gen-paths.mjs <path/to/restunts/src/restunts/asm/dseg.asm>
//   → writes src/track/elementPaths.generated.ts
// Reads each track element's connection records (TRKOBJINFO, 14 bytes each, pointed to by the
// first word of its trkObjectList entry) from the restunts disassembly's data segment: per path
// through the element its entry and exit points (edges of its tiles), and the connection types at
// both ends. Only this factual table is kept; the track check itself is our own code.
import { readFileSync, writeFileSync } from 'node:fs';

const lines = readFileSync(process.argv[2], 'utf8').split(/\r?\n/);
const labels = new Map();
const bytes = [];
let started = false;
for (const l of lines) {
  if (/^dseg segment/.test(l)) {
    started = true;
    continue;
  }
  if (!started) continue;
  const m = /^(\S+)?\s+(db|dw|dd)\s+(.+)$/.exec(l);
  if (!m) continue;
  if (m[1]) labels.set(m[1], bytes.length);
  const size = { db: 1, dw: 2, dd: 4 }[m[2]];
  const n = /^-?\d+$/.test(m[3].trim()) ? Number(m[3].trim()) : 0;
  for (let k = 0; k < size; k++) bytes.push((n >> (8 * k)) & 255);
}
const word = (o) => bytes[o] | (bytes[o + 1] << 8);
const sbyte = (o) => (bytes[o] > 127 ? bytes[o] - 256 : bytes[o]);

const listBase = labels.get('trkObjectList');
const count = bytes[labels.get('fence_TrkObjCodes')] + 1;
const paths = [];
for (let code = 0; code < count; code++) {
  const info = word(listBase + code * 14);
  if (!info) {
    paths.push([]);
    continue;
  }
  const n = bytes[info];
  const blocks = [];
  for (let b = 0; b < n; b++) {
    const o = info + b * 14;
    // [entry point, exit point, entry type, exit type, opponent run-up flag (si_opp3)]
    blocks.push([bytes[o + 1], bytes[o + 2], bytes[o + 3], bytes[o + 4], sbyte(o + 12)]);
  }
  paths.push(blocks);
}

const out = `// GENERATED by tools/stunts/gen-paths.mjs from the game's element table. Do not edit.
// Per element code, the paths through it: [entry point, exit point, entry type, exit type, run-up
// flag]. Points are edges of the element's tiles (see src/track/check.ts); a type is what the road
// is at that end (the next element must start with the same); the run-up flag is 0 for pieces that
// count towards the straight before a jump. Codes 0xB6..0xC5 are roads and ramps on slopes.

export const ELEMENT_PATHS: [number, number, number, number, number][][] = [
${paths.map((p, c) => `  ${JSON.stringify(p)}, // ${c.toString(16)}`).join('\n')}
];
`;
writeFileSync('src/track/elementPaths.generated.ts', out);
console.log(`wrote ${paths.length} elements`);
