// node tools/stunts/gen-elements.mjs <path/to/restunts/src/restunts/asm/dseg.asm>
//   → writes src/original/elementTable.generated.ts
// Reads the game's track element table ("trkObjectList", 14 bytes per element code) from the
// restunts disassembly (github.com/4d-stunts/restunts) and resolves each element's 3D shape name,
// rotation, paint job, footprint and overlay element. Only this factual table is kept; the shapes
// themselves are read at runtime from the player's own GAME1/GAME2.P3S.
import { readFileSync, writeFileSync } from 'node:fs';

const lines = readFileSync(process.argv[2], 'utf8').split(/\r?\n/);

// 1. Byte offsets of every label in the data segment (one db/dw/dd value per line).
const labels = new Map();
const bytes = [];
let started = false;
for (const l of lines) {
  if (/^dseg segment/.test(l)) {
    started = true;
    continue;
  }
  if (!started) continue;
  const m = /^(\S+)?\s+(db|dw|dd)\s+(.+)$/.exec(l);
  if (!m) continue;
  if (m[1]) labels.set(m[1], bytes.length);
  const size = { db: 1, dw: 2, dd: 4 }[m[2]];
  const n = /^-?\d+$/.test(m[3].trim()) ? Number(m[3].trim()) : 0;
  for (let k = 0; k < size; k++) bytes.push((n >> (8 * k)) & 255);
}
const word = (o) => bytes[o] | (bytes[o + 1] << 8);

// 2. Shape names, in the order the game loads them into its shape table (22-byte slots).
const names = [];
let inList = false;
let current = '';
for (const l of lines) {
  const start = /^(a[A-Za-z0-9_]+)\s+db\s+(\d+)/.exec(l);
  if (start && start[1] === 'aBarn') inList = true;
  if (!inList) continue;
  if (start) {
    if (current) names.push(current);
    current = '';
  } else if (/^\S/.test(l)) {
    names.push(current);
    break;
  }
  const v = /db\s+(\d+)/.exec(l);
  if (v && Number(v[1]) >= 32 && Number(v[1]) < 127) current += String.fromCharCode(Number(v[1]));
}

const shapesBase = labels.get('game3dshapes');
const listBase = labels.get('trkObjectList');
const count = bytes[labels.get('fence_TrkObjCodes')] + 1; // codes 0 .. fence code
const shapeName = (ptr) => {
  const i = (ptr - shapesBase) / 22;
  return Number.isInteger(i) && i >= 0 ? (names[i] ?? null) : null;
};

const table = [];
for (let code = 0; code < count; code++) {
  const o = listBase + code * 14;
  const shape = shapeName(word(o + 4));
  table.push({
    shape,
    lo: shapeName(word(o + 6)),
    rot: word(o + 2) / 256, // quarter turns, clockwise seen from above
    overlay: bytes[o + 8],
    paint: bytes[o + 9] === 255 ? 0 : bytes[o + 9],
    multi: bytes[o + 11], // 0 one tile, 1 two tiles N-S, 2 two tiles E-W, 3 four tiles
  });
}

const out = `// GENERATED by tools/stunts/gen-elements.mjs from the game's element table. Do not edit.
// Per element code: the original 3D shape (by name, read at runtime from GAME1/GAME2.P3S), its
// rotation in clockwise quarter turns, paint job, footprint, and an overlay element drawn with it.

export interface ElementShape {
  shape: string | null;
  lo: string | null;
  rot: number;
  overlay: number;
  paint: number;
  multi: number;
}

export const ELEMENT_SHAPES: ElementShape[] = ${JSON.stringify(table)};
`;
writeFileSync('src/original/elementTable.generated.ts', out);
console.log(`wrote ${table.length} elements; ${names.length} shape names`);
